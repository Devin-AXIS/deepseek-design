/** Validate a generated runtime against its source files and recorded output. */
import { createHash, randomUUID } from "node:crypto";
import {
  lstat,
  mkdir,
  readFile,
  readdir,
  readlink,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

const generatedDirectories = new Set([
  "node_modules",
  "dist",
  ".git",
  ".cache",
  ".turbo",
  "coverage",
]);

async function addTree(
  hash,
  root,
  path,
  excludeGenerated,
  excludedInputs = new Set(),
) {
  if (excludeGenerated && excludedInputs.has(resolve(path))) return;
  const info = await lstat(path);
  const name = relative(root, path).replaceAll("\\", "/");
  if (info.isSymbolicLink()) {
    if (!(await stat(path)).isFile())
      throw Error("Runtime inputs cannot contain directory symlinks: " + path);
    hash.update(JSON.stringify([name, "link", await readlink(path)]));
    hash.update(await readFile(path));
  } else if (info.isDirectory()) {
    for (const entry of (await readdir(path)).sort()) {
      if (
        excludeGenerated &&
        (generatedDirectories.has(entry) ||
          entry === ".DS_Store" ||
          entry.endsWith(".tsbuildinfo"))
      )
        continue;
      await addTree(
        hash,
        root,
        join(path, entry),
        excludeGenerated,
        excludedInputs,
      );
    }
  } else if (info.isFile()) {
    const bytes = await readFile(path);
    hash.update(JSON.stringify([name, bytes.length]));
    hash.update(bytes);
  }
}

/** Hash every input path, including added/deleted files, independent of mtimes.
 * @param {string[]} paths Source files or directories, in stable order.
 * @param {unknown} environment Build tool versions and target platform.
 * @param {string[]} excludedFiles Exact generated source files owned by the build.
 * @returns {Promise<string>} SHA-256 of source names, bytes and environment.
 */
export async function sourceFingerprint(
  paths,
  environment,
  excludedFiles = [],
) {
  const hash = createHash("sha256").update(JSON.stringify(environment));
  const excludedInputs = new Set(excludedFiles.map((path) => resolve(path)));
  for (let index = 0; index < paths.length; index++) {
    hash.update(String(index));
    await addTree(hash, paths[index], paths[index], true, excludedInputs);
  }
  return hash.digest("hex");
}

async function outputFingerprint(directory, requiredFiles) {
  for (const name of requiredFiles) {
    try {
      if (!(await lstat(join(directory, name))).isFile()) return null;
    } catch (error) {
      if (error.code === "ENOENT") return null;
      throw error;
    }
  }
  const hash = createHash("sha256");
  await addTree(hash, directory, directory, false);
  return hash.digest("hex");
}

/** Rebuild when source, tools or generated bytes differ from the successful build.
 * @param {{inputs:string[], environment:unknown, directory:string, requiredFiles:string[], stamp:string, build:()=>Promise<void>, force?:boolean, excludedInputs?:string[]}} options Build inputs, exact generated source exclusions and owned output paths.
 * @returns {Promise<boolean>} Whether the build ran.
 */
export async function ensureCachedRuntime(options) {
  const input = await sourceFingerprint(
    options.inputs,
    options.environment,
    options.excludedInputs,
  );
  let recorded;
  try {
    recorded = JSON.parse(await readFile(options.stamp, "utf8"));
  } catch (error) {
    if (error.code !== "ENOENT" && !(error instanceof SyntaxError)) throw error;
  }
  if (!options.force && recorded?.version === 1 && recorded.input === input) {
    const output = await outputFingerprint(
      options.directory,
      options.requiredFiles,
    );
    if (output !== null && output === recorded.output) return false;
  }
  // A failed rebuild must not leave a stamp that blesses an older runtime.
  await rm(options.stamp, { force: true });
  await options.build();
  const output = await outputFingerprint(
    options.directory,
    options.requiredFiles,
  );
  if (output === null)
    throw Error("HyperFrames build did not produce the required runtime files");
  const completedInput = await sourceFingerprint(
    options.inputs,
    options.environment,
    options.excludedInputs,
  );
  if (completedInput !== input)
    throw Error(
      "Runtime inputs changed during compilation; run the build again",
    );
  await mkdir(dirname(options.stamp), { recursive: true });
  const temporary = options.stamp + "." + randomUUID() + ".tmp";
  try {
    await writeFile(
      temporary,
      JSON.stringify({ version: 1, input, output }) + "\n",
    );
    await rename(temporary, options.stamp);
  } finally {
    await rm(temporary, { force: true });
  }
  return true;
}
